import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import ffmpegPath from 'ffmpeg-static';

const root = fileURLToPath(new URL('../', import.meta.url));
const outputDir = path.join(root, 'media/previews');
await fs.mkdir(outputDir, { recursive: true });
const sources = new Set();
for (const file of ['constants.ts', 'App.tsx']) {
  const code = await fs.readFile(path.join(root, file), 'utf8');
  for (const match of code.matchAll(/import\s+\w+\s+from\s+['"](\.\/media\/[^'"]+)['"]/g)) {
    if (/\.(webp|png|jpe?g|mp4|mov)$/i.test(match[1])) sources.add(match[1]);
  }
}
const imports = [];
const entries = [];
let originalImageBytes = 0;
let previewImageBytes = 0;
let videoCount = 0;
for (const [index, source] of [...sources].sort().entries()) {
  const input = path.join(root, source);
  const bytes = await fs.readFile(input);
  const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 12);
  imports.push(`import source${index} from ${JSON.stringify(source)};`);
  if (/\.(mp4|mov)$/i.test(source)) {
    const name = `${hash}-poster.webp`;
    const output = path.join(outputDir, name);
    try { await fs.access(output); } catch {
      let result = spawnSync(ffmpegPath, ['-hide_banner', '-loglevel', 'error', '-ss', '1', '-i', input, '-frames:v', '1', '-vf', "scale='min(480,iw)':-2", '-f', 'image2pipe', '-vcodec', 'mjpeg', 'pipe:1']);
      if (result.status !== 0 || !result.stdout.length) throw new Error(`Poster generation failed for ${source}: ${result.stderr}`);
      await sharp(result.stdout).webp({ quality: 80 }).toFile(output);
    }
    imports.push(`import poster${index} from './media/previews/${name}';`);
    entries.push(`  [source${index}]: { poster: poster${index} },`);
    videoCount++;
  } else {
    const metadata = await sharp(input).metadata();
    const widths = [...new Set([Math.min(480, metadata.width), Math.min(960, metadata.width)])];
    const variants = [];
    for (const width of widths) {
      const name = `${hash}-${width}.webp`;
      const output = path.join(outputDir, name);
      try { await fs.access(output); } catch {
        await sharp(input).rotate().resize({ width, withoutEnlargement: true }).webp({ quality: 80 }).toFile(output);
      }
      const actual = await sharp(output).metadata();
      const variable = `image${index}_${width}`;
      imports.push(`import ${variable} from './media/previews/${name}';`);
      variants.push({ variable, width: actual.width });
      if (width === widths[0]) previewImageBytes += (await fs.stat(output)).size;
    }
    originalImageBytes += bytes.length;
    entries.push(`  [source${index}]: { src: ${variants[0].variable}, srcSet: ${variants.map(v=>`${v.variable} + ' ${v.width}w'`).join(" + ', ' + ")} },`);
  }
}
await fs.writeFile(path.join(root, 'media-previews.ts'), `// Generated by npm run media:previews. Keep original media for full-quality sources.\n${imports.join('\n')}\n\nexport interface MediaPreview {\n  src?: string;\n  srcSet?: string;\n  poster?: string;\n}\n\nexport const MEDIA_PREVIEWS: Record<string, MediaPreview> = {\n${entries.join('\n')}\n};\n`);
console.log(`Generated ${sources.size - videoCount} responsive image sets and ${videoCount} video posters.`);
console.log(`Card-size images: ${originalImageBytes.toLocaleString()} -> ${previewImageBytes.toLocaleString()} bytes (${Math.round((1 - previewImageBytes / originalImageBytes) * 100)}% smaller).`);
